// Turns src/assets/figure.glb into a TypeScript module holding the file as base64,
// so the game bundle carries the character model itself. Run after replacing the GLB:
//   node scripts/embed-model.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const data = readFileSync('src/assets/figure.glb').toString('base64');
writeFileSync('src/assets/figureData.ts', `// Generated by scripts/embed-model.mjs. Do not edit.\nexport default '${data}';\n`);
console.log(`figureData.ts written (${(data.length / 1e6).toFixed(1)} MB of base64)`);
